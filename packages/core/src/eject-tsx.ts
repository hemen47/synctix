/**
 * Eject to TSX — a one-way door out.
 *
 * A power user who has gone as far as the editor takes them should be able to leave with
 * tscircuit source rather than a JSON blob. This generates that source.
 *
 * **It is one-way, deliberately.** Round-tripping graphical edits back through generated
 * TSX would mean the document had two authorities, and reconciling them is where every
 * schematic tool of this shape has come apart. The document stays circuit-json; TSX is an
 * input format going in (`compileTsx`) and a export format going out (here), and neither
 * direction pretends to be lossless.
 *
 * ## What is lost
 *
 * - **Anything with no tscircuit element.** Net labels and power symbols become `<trace>`
 *   connections to a named net; an unsupported ftype becomes a `<chip>` with a comment.
 * - **The sidecar.** Constraints, agent notes and provenance have no representation in
 *   tscircuit source. Placement does survive, as `schX`/`schY` and `pcbX`/`pcbY`.
 * - **Footprints we could not name.** A footprint resolved from a KiCad module has no
 *   footprinter string, so the component is emitted without one and flagged in a comment.
 *
 * Every loss is written into the generated file as a comment, so the person reading it
 * finds out from the file rather than from a surprise.
 */

import type { AnyCircuitElement } from "circuit-json"
import type { Design } from "./types"
import { buildIndex, electricalNets } from "./index-view"
import { findPlacement } from "./manual-edits"

/** ftype → tscircuit element name, for the ftypes that have a direct equivalent. */
const ELEMENT_FOR_FTYPE: Record<string, string> = {
  simple_resistor: "resistor",
  simple_capacitor: "capacitor",
  simple_inductor: "inductor",
  simple_diode: "diode",
  simple_led: "led",
  simple_ground: "ground",
  simple_power_source: "powersource",
  simple_voltage_source: "voltagesource",
  simple_chip: "chip",
  simple_op_amp: "opamp",
  simple_mosfet: "mosfet",
  simple_transistor: "transistor",
  simple_crystal: "crystal",
  simple_fuse: "fuse",
  simple_switch: "switch",
  simple_push_button: "pushbutton",
  simple_potentiometer: "potentiometer",
  simple_battery: "battery",
  simple_pin_header: "pinheader",
}

/** Which circuit-json prop carries the value, and how it is spelled as a tscircuit prop. */
const VALUE_PROP: Record<string, string> = {
  resistance: "resistance",
  capacitance: "capacitance",
  inductance: "inductance",
  voltage: "voltage",
  current: "current",
}

export interface EjectOptions {
  /** Board outline, in mm. Defaults to a size that comfortably holds the placement. */
  board?: { width: number; height: number }
  /** Name used for the exported component. */
  name?: string
}

export interface EjectResult {
  code: string
  /** Everything the generated source could not express, in the order it was found. */
  limitations: string[]
}

export const ejectToTsx = (design: Design, options: EjectOptions = {}): EjectResult => {
  const view = buildIndex(design.circuit)
  const limitations: string[] = []
  const lines: string[] = []

  const componentLines: string[] = []
  for (const component of view.components.values()) {
    componentLines.push(...emitComponent(design, view, component, limitations))
  }

  const traceLines = emitTraces(design, view, limitations)

  const board = options.board ?? inferBoardSize(design)
  const name = options.name ?? "Circuit"

  lines.push("// Generated by SYNTRIX — eject to TSX.")
  lines.push("//")
  lines.push("// This is a one-way export. Editing it does not change the SYNTRIX design,")
  lines.push("// and re-importing it creates a new document rather than updating this one.")
  if (limitations.length > 0) {
    lines.push("//")
    lines.push("// Not carried across:")
    for (const limitation of limitations) lines.push(`//   - ${limitation}`)
  }
  lines.push("")
  lines.push(`export const ${name} = () => (`)
  lines.push(`  <board width="${board.width}mm" height="${board.height}mm">`)
  for (const line of componentLines) lines.push(`    ${line}`)
  if (traceLines.length > 0) {
    lines.push("")
    for (const line of traceLines) lines.push(`    ${line}`)
  }
  lines.push("  </board>")
  lines.push(")")
  lines.push("")

  return { code: lines.join("\n"), limitations }
}

type IndexedView = ReturnType<typeof buildIndex>
type SourceComponent = Extract<AnyCircuitElement, { type: "source_component" }>

const emitComponent = (
  design: Design,
  view: IndexedView,
  component: SourceComponent,
  limitations: string[],
): string[] => {
  const record = component as unknown as Record<string, unknown>
  const ftype = component.ftype ?? "simple_chip"
  const element = ELEMENT_FOR_FTYPE[ftype]

  const props: string[] = [`name="${component.name}"`]

  if (!element) {
    limitations.push(
      `${component.name}: ftype "${ftype}" has no tscircuit element; emitted as <chip>`,
    )
  }

  // The value, taken from whichever numeric prop this ftype uses. The display string is
  // preferred when present: it is what the author wrote ("10k"), and tscircuit parses it.
  for (const [field, prop] of Object.entries(VALUE_PROP)) {
    const display = record[`display_${field}`]
    const numeric = record[field]
    if (typeof display === "string") {
      props.push(`${prop}="${display}"`)
      break
    }
    if (typeof numeric === "number") {
      props.push(`${prop}="${numeric}"`)
      break
    }
  }

  const footprint = footprintString(component)
  if (footprint) {
    props.push(`footprint="${footprint}"`)
  } else if (view.portsByComponent.get(component.source_component_id)?.length) {
    limitations.push(`${component.name}: no footprinter string, emitted without a footprint`)
  }

  const sch = findPlacement(design.manualEdits, "schematic", component.name)
  if (sch) props.push(`schX={${round(sch.center.x)}} schY={${round(sch.center.y)}}`)
  const pcb = findPlacement(design.manualEdits, "pcb", component.name)
  if (pcb) props.push(`pcbX={${round(pcb.center.x)}} pcbY={${round(pcb.center.y)}}`)

  const rotation = design.meta[component.source_component_id]?.rotationDeg
  if (rotation !== undefined) props.push(`schRotation={${rotation}}`)

  return [`<${element ?? "chip"} ${props.join(" ")} />`]
}

/**
 * Footprint, if we can name one tscircuit understands.
 *
 * Only a footprinter string round-trips — it is the one form tscircuit can rebuild pads
 * from. A footprint that arrived as pcb elements (from a KiCad module, say) has no such
 * string, and inventing one would be worse than omitting it.
 */
const footprintString = (component: SourceComponent): string | undefined => {
  const record = component as unknown as Record<string, unknown>
  const declared = record["footprinter_string"] ?? record["footprint"]
  // A part reference in the sidecar may well name a footprint, but resolving it needs
  // @syntrix/parts, which core does not depend on (the dependency runs the other way).
  // The exporter, which has both, fills that gap.
  return typeof declared === "string" ? declared : undefined
}

/**
 * Traces.
 *
 * circuit-json models connectivity as nets of ports; tscircuit models it as `<trace>`
 * elements between two selectors. A net with more than two members becomes one trace per
 * additional member, all chained to the first — electrically identical, and closer to how
 * a person would have drawn it than a star from an invisible centre.
 */
const emitTraces = (design: Design, view: IndexedView, limitations: string[]): string[] => {
  const lines: string[] = []

  for (const net of electricalNets(view)) {
    const selectors: string[] = []
    for (const portId of net.ports) {
      const port = view.byId.get(portId)
      if (!port || port.type !== "source_port" || !port.source_component_id) continue
      const component = view.components.get(port.source_component_id)
      if (!component) continue
      selectors.push(`.${component.name} > .${port.name ?? `pin${port.pin_number}`}`)
    }

    if (selectors.length < 2) {
      if (net.name && selectors.length === 1) {
        limitations.push(`net "${net.name}" has one member; no trace emitted`)
      }
      continue
    }

    const [first, ...rest] = selectors
    if (!first) continue
    for (const selector of rest) {
      lines.push(`<trace from="${first}" to="${selector}" />`)
    }
  }

  return lines
}

/** A board big enough for what is placed, with a margin, rounded up to whole mm. */
const inferBoardSize = (design: Design): { width: number; height: number } => {
  const points = [
    ...(design.manualEdits.pcb_placements ?? []).map((p) => p.center),
    ...(design.manualEdits.schematic_placements ?? []).map((p) => p.center),
  ]
  if (points.length === 0) return { width: 30, height: 30 }

  const xs = points.map((p) => Math.abs(p.x))
  const ys = points.map((p) => Math.abs(p.y))
  return {
    width: Math.max(20, Math.ceil(Math.max(...xs) * 2 + 10)),
    height: Math.max(20, Math.ceil(Math.max(...ys) * 2 + 10)),
  }
}

const round = (n: number): number => Math.round(n * 1000) / 1000
